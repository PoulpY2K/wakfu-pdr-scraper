CREATE TABLE author
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handle        TEXT        NOT NULL UNIQUE, -- Ankama nickname + tag, e.g. KozmicDaddy#1419
    nickname      TEXT        NOT NULL,
    profile_url   TEXT        NOT NULL,
    first_seen_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE topic
(
    id            BIGINT PRIMARY KEY,            -- forum id
    author_id     BIGINT REFERENCES author (id), -- null until its first page is fetched
    title         TEXT        NOT NULL,
    url           TEXT        NOT NULL,
    pinned        BOOLEAN     NOT NULL,
    reply_count   INTEGER     NOT NULL,
    first_seen_at TIMESTAMPTZ NOT NULL,
    last_seen_at  TIMESTAMPTZ NOT NULL
);

CREATE TABLE post
(
    id            BIGINT PRIMARY KEY,   -- forum id, from id="entry…"
    topic_id      BIGINT      NOT NULL REFERENCES topic (id),
    author_id     BIGINT      NOT NULL REFERENCES author (id),
    posted_at     TIMESTAMPTZ NOT NULL,
    content       TEXT        NOT NULL,
    content_hash  TEXT        NOT NULL, -- SHA-256 hex, to detect edits later
    first_seen_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX post_topic_id_idx ON post (topic_id);
CREATE INDEX post_author_id_idx ON post (author_id);

CREATE TABLE notification
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id            BIGINT      NOT NULL REFERENCES post (id),
    type               TEXT        NOT NULL CHECK (type IN ('NEW_TOPIC', 'NEW_POST')),
    channel            TEXT        NOT NULL CHECK (channel IN ('GLOBAL', 'BOARD', 'RUMORS')),
    status             TEXT        NOT NULL CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    attempts           INTEGER     NOT NULL DEFAULT 0,
    discord_message_id TEXT,
    last_error         TEXT,
    created_at         TIMESTAMPTZ NOT NULL,
    sent_at            TIMESTAMPTZ,
    CONSTRAINT notification_post_channel_uk UNIQUE (post_id, channel)
);
CREATE INDEX notification_pending_idx ON notification (created_at) WHERE status = 'PENDING';